const mm = 1e-3, cm = 1e-2, cm2 = 1e-4, cm3 = 1e-6, cm4 = 1e-8, cm6 = 1e-12;

function buildUe(r) {
  const [des, massa, bw, bf, D, t, A, Ix, Wx, rx, Iy, Wy, ry, It, Cw, x0, xg, r0] = r;
  const tc = t / 10;                                             // cm
  const am = bw / 10 - tc, bm = bf / 10 - tc, cmm = D / 10 - tc / 2;
  const Jc = (am + 2 * bm + 2 * cmm) * tc ** 3 / 3;              // cm⁴
  return [des, {
    shape: 'Ue', designacao: des, massa,
    dims: { bw: bw * mm, bf: bf * mm, D: D * mm, t: t * mm, ri: t * mm },   // ri = t (NBR 6355:2012 Tab. A.3)
    A: A * cm2, Iz: Ix * cm4, Iy: Iy * cm4, Sz: Wx * cm3, Sy: Wy * cm3, rz: rx * cm, ry: ry * cm,
    J: Jc * cm4, JTab: It * cm4, Cw: Cw * cm6, x0: x0 * cm, xg: xg * cm, r0: r0 * cm,
    fonte: 'ABNT NBR 6355:2012 Tab. A.3',
  }];
}

function buildL(r) {
  const [des, massa, , b, , t, A, Ix, Wx, rx, Iy, Wy, ry, It, Cw, x0, xg, r0] = r;
  const tc = t / 10;
  const Jc = (2 * b / 10 - tc) * tc ** 3 / 3;
  return [des, {
    shape: 'L', designacao: des, massa,
    dims: { b: b * mm, t: t * mm },
    A: A * cm2, Iz: Ix * cm4, Iy: Iy * cm4, Sz: Wx * cm3, Sy: Wy * cm3, rz: rx * cm, ry: ry * cm,
    J: Jc * cm4, JTab: It * cm4, Cw: Cw * cm6, x0: x0 * cm, xg: xg * cm, r0: r0 * cm,
    fonte: 'ABNT NBR 6355:2012 Tab. A.1',
  }];
}

export const CF_PROFILES = Object.fromEntries([...UE.map(buildUe), ...LCANT.map(buildL)]);

/** Names of the catalogue (optionally only one shape: 'Ue' | 'L'). */
export function cfNames(shape) {
  return Object.keys(CF_PROFILES).filter(n => !shape || CF_PROFILES[n].shape === shape);
}

/** Profile (SI) or null. */
export function cfProfile(name) { return CF_PROFILES[name] || null; }

/** `sec` object ready for nbr14762.check (SI; same object as the catalogue entry, copied). */
export function cfSection(name) {
  const p = CF_PROFILES[name];
  return p ? { ...p, dims: { ...p.dims } } : null;
}
