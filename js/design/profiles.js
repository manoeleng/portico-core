function buildChannels(table) {
  const out = {};
  for (const [name, [[d, bf, tw, tf, A, Ix, Wx, rx, Iy, Wy, ry, x], [Zx, Zy, J, Cw, aisc]]] of Object.entries(table)) {
    out[name] = { shape: 'channel', aisc, dims: { d: d / 1000, bf: bf / 1000, tw: tw / 1000, tf: tf / 1000 },
      tab: { A: A / 1e4, Iz: Ix / 1e8, Iy: Iy / 1e8, Sz: Wx / 1e6, Sy: Wy / 1e6, Zz: Zx / 1e6, Zy: Zy / 1e6,
        rz: rx / 100, ry: (ry ?? Math.sqrt(Iy / A)) / 100, x: x / 100, J: J / 1e8, Cw: Cw / 1e12 } };
  }
  return out;
}

// Families → { name → { shape, dims(m) } }
function buildFamily(table, shape, keys) {
  const out = {};
  for (const [name, v] of Object.entries(table)) {
    const dims = {};
    keys.forEach((k, i) => { dims[k] = v[i] / 1000; });
    out[name] = { shape, dims };
  }
  return out;
}

